# PostgreSQL: PK-BIGINT + bigserial                                            #
# --------------------------------------------------------------------------- #

def _pg_serial_for(table_name: str) -> str:
    """Имя sequence для serial-PK колонки id (по конвенции SQLAlchemy/PG)."""
    return f"{table_name}_id_seq"


def _pg_autoincrement_ok(conn, table: str) -> bool:
    """Есть ли у id таблицы механизм автоинкремента (identity или serial)."""
    row = conn.execute(
        text(
            "SELECT column_default, is_identity FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = :t "
            "AND column_name = 'id'"
        ),
        {"t": table},
    ).first()
    if row is None:
        return False
    default, is_identity = row[0] or "", row[1] or "NO"
    return is_identity == "YES" or "nextval(" in default.lower()


def _pg_bigserial_pk(engine: Engine, table_name: str) -> None:
    """Гарантировать BIGINT-автоинкремент PK «id» таблицы (идемпотентно).

    Исторически PK создавался как INTEGER GENERATED BY DEFAULT AS IDENTITY —
    последовательность identity ограничена int32 и переполняется примерно на
    2,1 млрд записей. Переводим колонку в BIGINT и переключаем по умолчанию
    на bigserial-последовательность (CREATE SEQUENCE ... AS bigint), starting
    from текущего MAX(id). Таблицы без колонки id / уже имеющие nextval- или
    identity-PG10+-формат пропускаются.
    """
    if not _table_exists(engine, table_name):
        return
    if "id" not in _columns(engine, table_name):
        return
    with engine.begin() as conn:
        if _pg_autoincrement_ok(conn, table_name):
            return
        log.info("Миграция v9: включаю bigserial-автоинкремент для %s.id", table_name)
        # 1. Тип колонки -> bigint (identity, если он был, снимается самим ALTER TYPE)
        conn.execute(text(f'ALTER TABLE "{table_name}" ALTER COLUMN "id" TYPE bigint'))
        # 2. Собственная BIGINT-последовательность, старт от текущего максимума
        seq = _pg_serial_for(table_name)
        max_id = conn.execute(text(f'SELECT COALESCE(MAX("id"), 0) FROM "{table_name}"')).scalar() or 0
        conn.execute(text(f'DROP SEQUENCE IF EXISTS "{seq}"'))
        conn.execute(
            text(
                f'CREATE SEQUENCE "{seq}" AS bigint '
                f"INCREMENT BY 1 NO MINVALUE NO MAXVALUE START WITH {int(max_id) + 1} "
                "NO CYCLE"
            )
        )
        conn.execute(
            text(
                f'ALTER TABLE ONLY "{table_name}" '
                f"ALTER COLUMN \"id\" SET DEFAULT nextval('{seq}'::regclass)"
            )
        )
        # sequence принадлежит колонке (будет удалён вместе с ней)
        conn.execute(text(f"ALTER SEQUENCE \"{seq}\" OWNED BY \"{table_name}\".\"id\""))


