    cols = _columns(engine, "user_roles")
    if "first_seen" not in cols:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE user_roles ADD COLUMN first_seen TIMESTAMP"))
            conn.execute(text("ALTER TABLE user_roles ADD COLUMN last_seen TIMESTAMP"))
