def _recreate_table_pg(engine: Engine, table_name: str) -> bool:
    """Пересоздать таблицу по актуальным метаданным модели, сохранив данные.

    Используется миграцией v6 для САМОВОССТАНОВЛЕНИЯ старых схем: если
    таблица существует, но её структура разошлась с моделью (например, PK
    создан без автоинкремента), она пересоздаётся с сохранением общих колонок.
    Возвращает True, если таблица была пересоздана.
    """
    from app.models.entities import Base

    if not _table_exists(engine, table_name):
        with engine.begin() as conn:
            Base.metadata.tables[table_name].create(bind=conn, checkfirst=True)
        _pg_bigserial_pk(engine, table_name)
        return True

    model_cols = {c.name for c in Base.metadata.tables[table_name].columns}
    db_cols = _columns(engine, table_name)
    # «кривой» PK: id без механизма автоинкремента (ни identity, ни serial)
    broken_pk = False
    with engine.connect() as conn:
        if "id" in db_cols and not _pg_autoincrement_ok(conn, table_name):
            broken_pk = True
    missing_cols = model_cols - db_cols
    if not broken_pk and not missing_cols:
        return False

    log.warning(
        "Миграция v6: таблица %s расходится со схемой модели "
        "(битый PK: %s, отсутствующие колонки: %s) — пересоздаю.",
        table_name, broken_pk, ", ".join(sorted(missing_cols)) or "—",
    )
    backup = f"_mig_{table_name}_old"
    with engine.begin() as conn:
        conn.execute(text(f'ALTER TABLE "{table_name}" RENAME TO "{backup}"'))
    try:
        with engine.begin() as conn:
            Base.metadata.tables[table_name].create(bind=conn)
        _pg_bigserial_pk(engine, table_name)
        with engine.begin() as conn:
            new_cols = {c["name"] for c in inspect(engine).get_columns(table_name)}
            old_cols = [c["name"] for c in inspect(engine).get_columns(backup)]
            common = [c for c in old_cols if c in new_cols]
            if common:
                cols_sql = ", ".join(f'"{c}"' for c in common)
                conn.execute(text(
                    f'INSERT INTO "{table_name}" ({cols_sql}) '
                    f'SELECT {cols_sql} FROM "{backup}"'
                ))
            # синхронизируем sequence после переноса явных id
            seq = _pg_serial_for(table_name)
            if conn.execute(
                text("SELECT 1 FROM information_schema.sequences WHERE sequence_name = :s"),
                {"s": seq},
            ).first():
                max_id = conn.execute(
                    text(f'SELECT COALESCE(MAX("id"), 0) FROM "{table_name}"')
                ).scalar() or 0
                conn.execute(
                    text(f"SELECT setval('{seq}', :v, true)"), {"v": int(max_id) + 1}
                )
            conn.execute(text(f'DROP TABLE "{backup}"'))
    except Exception:
        # откатываем переименование, чтобы не оставить базу без таблицы
        with engine.begin() as conn:
            if not _table_exists(engine, table_name):
                conn.execute(text(f'ALTER TABLE "{backup}" RENAME TO "{table_name}"'))
        raise
    return True


