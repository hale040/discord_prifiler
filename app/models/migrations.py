def _v04_compact_raw_json(engine: Engine) -> None:
    """v4: очистка messages.raw_json от полного дампа Discord-объектов.

    Исторически в каждую строку messages писался полный ``msg.to_dict()``
    (десятки КБ на сообщение) — база раздувалась в разы, а анализ использует
    только смапленные колонки. Теперь raw_json сообщений не сохраняется вовсе
    (STORE_RAW_JSON=0 по умолчанию), а старые дампы вычищаются этим шагом
    (остаются только строки длиннее 4096 символов — типичный размер полного дампа).

    Идемпотентно: повторный запуск ничего не меняет. Перед очисткой делается
    SQL-бэкап затронутых строк в таблицу _backup_v4_raw_json (в PG whole-file
    копия файла БД недоступна; точечный бэкап содержимого безопаснее и меньше).
    """
    with engine.begin() as conn:
        n = conn.execute(
            text("SELECT COUNT(*) FROM messages WHERE raw_json IS NOT NULL "
                 "AND LENGTH(raw_json) > 4096")
        ).scalar() or 0
        if not n:
            return
        conn.execute(
            text(
                "CREATE TABLE IF NOT EXISTS _backup_v4_raw_json ("
                " id BIGINT, raw_json TEXT, backed_up_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)"
            )
        )
        conn.execute(
            text(
                "INSERT INTO _backup_v4_raw_json (id, raw_json) "
                "SELECT id, raw_json FROM messages "
                "WHERE raw_json IS NOT NULL AND LENGTH(raw_json) > 4096"
            )
        )
    with engine.begin() as conn:
        conn.execute(
            text("UPDATE messages SET raw_json = NULL "
                 "WHERE raw_json IS NOT NULL AND LENGTH(raw_json) > 4096")
        )
    log.info("Миграция v4: очищено raw_json в %s сообщениях; бэкап: _backup_v4_raw_json", n)


